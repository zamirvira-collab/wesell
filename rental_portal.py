class DatabaseConnection:
    """Keep existing conn.execute(...).fetchone() code compatible with PostgreSQL."""

    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, params=None):
        cursor = self.connection.cursor(cursor_factory=RealDictCursor)
        cursor.execute(query.replace("?", "%s"), params or ())
        return cursor


@contextmanager
def db():
    database_url = os.environ.get("DATABASE_URL", "").strip()
    if not database_url:
        raise RuntimeError("DATABASE_URL is missing from Render environment variables")

    # Render sometimes provides the older postgres:// scheme.
    if database_url.startswith("postgres://"):
        database_url = "postgresql://" + database_url[len("postgres://"):]

    connection = psycopg2.connect(database_url, connect_timeout=15)
    try:
        yield DatabaseConnection(connection)
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


