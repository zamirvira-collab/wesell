@rental_portal.route(
    "/register",
    methods=["GET", "POST"]
)
def register():

    if request.method == "POST":
        if not secrets.compare_digest(request.form.get("csrf", ""), csrf_token()):
            return "Invalid request. Refresh the page and try again.", 400


        company_name = request.form.get(
            "company_name", ""
        ).strip()[:150]

        contact_name = request.form.get(
            "contact_name", ""
        ).strip()[:120]

        email = request.form.get(
            "email", ""
        ).strip().lower()[:254]

        password = request.form.get(
            "password", ""
        )

        phone = request.form.get(
            "phone", ""
        ).strip()[:30]

        city = request.form.get(
            "city", ""
        ).strip()[:120]

        website = request.form.get(
            "website", ""
        ).strip()[:500]

        if (
            not company_name
            or not contact_name
            or not re.fullmatch(
                r"[^@\s]+@[^@\s]+\.[^@\s]+",
                email
            )
            or len(password) < 10
        ):

            flash(
                "Please complete all required fields. "
                "Password must contain at least 10 characters."
            )

        else:

            try:

                with db() as conn:

                    conn.execute(
                        """
                        INSERT INTO rental_companies
                        (
                            company_name,
                            contact_name,
                            email,
                            password_hash,
                            phone,
                            city,
                            website,
                            approved
                        )
                        VALUES (?,?,?,?,?,?,?,0)
                        """,
                        (
                            company_name,
                            contact_name,
                            email,
                            generate_password_hash(password),
                            phone,
                            city,
                            website
                        )
                    )

                flash(
                    "Registration received. "
                    "Your company is awaiting WE-SELL approval."
                )

                return redirect(
                    url_for("rental_portal.login")
                )

            except IntegrityError:

                flash(
                    "This email is already registered."
                )

